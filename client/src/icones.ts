/**
 * Icônes de l'interface, dessinées ici en pixels (grille de 12 × 12, `#` = pixel plein)
 * et converties en SVG inline : pas de pack d'icônes ni de police tierce, et le même
 * esprit pixel art que le jeu. Décoratives (`aria-hidden`) : chaque bouton porte son
 * propre libellé accessible.
 */

/** Chemin SVG d'une grille de pixels : un rectangle par suite de pixels pleins d'une ligne. */
export function cheminPixels(lignes: readonly string[]): string {
  const morceaux: string[] = [];
  lignes.forEach((ligne, y) => {
    let x = 0;
    while (x < ligne.length) {
      if (ligne[x] !== '#') {
        x++;
        continue;
      }
      const debut = x;
      while (ligne[x] === '#') x++;
      morceaux.push(`M${debut} ${y}h${x - debut}v1h${debut - x}z`);
    }
  });
  return morceaux.join('');
}

